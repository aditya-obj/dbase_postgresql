// Usage: dart run tool/generate_keywords.dart path/to/kwlist.h [pgVersion]

import 'dart:io';

const _output = 'lib/src/sql/sql_keyword_table.dart';
const _categories = {
  'UNRESERVED_KEYWORD': 'unreservedKeywords',
  'COL_NAME_KEYWORD': 'colNameKeywords',
  'TYPE_FUNC_NAME_KEYWORD': 'typeFuncNameKeywords',
  'RESERVED_KEYWORD': 'reservedKeywords',
};

void main(List<String> args) {
  if (args.isEmpty) {
    stderr.writeln('Usage: generate_keywords.dart <kwlist.h> [source label]');
    exitCode = 64;
    return;
  }
  final source = args.length > 1 ? args[1] : 'master';
  final entry = RegExp(
    r'^PG_KEYWORD\("([a-z_]+)",\s*\w+,\s*(\w+),\s*\w+\)\s*(/\*.*\*/)?$',
  );
  final words = {for (final name in _categories.values) name: <String>[]};
  for (final line in File(args[0]).readAsLinesSync()) {
    if (!line.startsWith('PG_KEYWORD(')) continue;
    final match = entry.firstMatch(line.trim());
    if (match == null) throw FormatException('Unrecognised entry: $line');
    final category = _categories[match[2]];
    if (category == null) throw StateError('Unknown category ${match[2]}');
    words[category]!.add(match[1]!);
  }

  final out = StringBuffer()
    ..writeln('// File: sql_keyword_table.dart')
    ..writeln('// Purpose: PostgreSQL keyword names by grammar category.')
    ..writeln('//')
    ..writeln('// GENERATED by tool/generate_keywords.dart - do not edit.')
    ..writeln('// Ported from src/include/parser/kwlist.h ($source) -')
    ..writeln('// PostgreSQL License, (c) 1996-2026 PostgreSQL Global')
    ..writeln('// Development Group, (c) 1994 The Regents of the University')
    ..writeln('// of California. See THIRD_PARTY_NOTICES.')
    ..writeln();
  for (final MapEntry(:key, :value) in words.entries) {
    out
      ..writeln('/// ${value.length} keywords; space-separated, ASCII order.')
      ..writeln('const $key =');
    final lines = <String>[];
    var line = StringBuffer();
    for (final word in value) {
      if (line.length + word.length + 1 > 68) {
        lines.add(line.toString());
        line = StringBuffer();
      }
      line.write('$word ');
    }
    lines.add(line.toString().trimRight());
    for (var i = 0; i < lines.length; i++) {
      final end = i == lines.length - 1 ? "';" : "'";
      out.writeln("    '${lines[i]}$end");
    }
    out.writeln();
  }
  File(_output).writeAsStringSync('${out.toString().trimRight()}\n');
  stdout.writeln('Wrote $_output');
}
