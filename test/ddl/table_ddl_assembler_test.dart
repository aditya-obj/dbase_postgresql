import 'package:dbase_postgresql/catalog.dart';
import 'package:dbase_postgresql/ddl.dart';
import 'package:test/test.dart';

import 'table_ddl_test_rows.dart';

const pg17 = TableDdlAssembler(serverVersionNum: 170004);
const pg18 = TableDdlAssembler(serverVersionNum: 180001);

void main() {
  test('plain table: columns, inline PK/UNIQUE/CHECK, FK as trailing '
      'ALTER', () {
    final ddl = pg17.assemble(
      TableDdlSource(
        header: headerRow(),
        columns: [
          columnRow(1, 'id', 'integer', {'attnotnull': 't'}),
          columnRow(2, 'code', 'character varying(20)', {
            'collation': 'pg_catalog."C"',
            'default_or_generation_expr': "'new'::character varying",
          }),
          columnRow(3, 'qty', 'numeric(10,2)'),
          columnRow(4, 'customer_id', 'integer'),
        ],
        constraints: [
          constraintRow('orders_pkey', 'p', 'PRIMARY KEY (id)'),
          constraintRow('orders_code_key', 'u', 'UNIQUE (code)'),
          constraintRow('qty_positive', 'c', 'CHECK (qty > 0::numeric)'),
          constraintRow(
            'orders_customer_fk',
            'f',
            'FOREIGN KEY (customer_id) REFERENCES public.customers(id)',
          ),
        ],
      ),
    );
    expect(
      ddl,
      'CREATE TABLE public.orders (\n'
      '    id integer NOT NULL,\n'
      '    code character varying(20) COLLATE pg_catalog."C" '
      "DEFAULT 'new'::character varying,\n"
      '    qty numeric(10,2),\n'
      '    customer_id integer,\n'
      '    CONSTRAINT orders_pkey PRIMARY KEY (id),\n'
      '    CONSTRAINT orders_code_key UNIQUE (code),\n'
      '    CONSTRAINT qty_positive CHECK (qty > 0::numeric)\n'
      ');\n'
      '\n'
      'ALTER TABLE public.orders ADD CONSTRAINT orders_customer_fk '
      'FOREIGN KEY (customer_id) REFERENCES public.customers(id);\n'
      '\n'
      'ALTER TABLE public.orders OWNER TO app;\n',
    );
  });

  test('NOT VALID check goes to a trailing ALTER; inherited constraints '
      'are skipped', () {
    final ddl = pg17.assemble(
      TableDdlSource(
        header: headerRow(),
        columns: [columnRow(1, 'qty', 'integer')],
        constraints: [
          constraintRow('qty_small', 'c', 'CHECK (qty < 10) NOT VALID', {
            'convalidated': 'f',
          }),
          constraintRow('from_parent', 'c', 'CHECK (qty > 0)', {
            'conislocal': 'f',
          }),
        ],
      ),
    );
    expect(
      ddl,
      contains(
        'ALTER TABLE public.orders ADD CONSTRAINT qty_small '
        'CHECK (qty < 10) NOT VALID;',
      ),
    );
    expect(ddl, isNot(contains('from_parent')));
    expect(
      ddl,
      isNot(contains('CONSTRAINT qty_small CHECK (qty < 10) NOT VALID,')),
    );
  });

  group('identity, generated and default columns', () {
    test('identity with a non-default start; default options omitted', () {
      final ddl = pg17.assemble(
        TableDdlSource(
          header: headerRow(),
          columns: [
            columnRow(1, 'id', 'bigint', {
              'attidentity': 'a',
              'attnotnull': 't',
            }),
            columnRow(2, 'n', 'integer', {'attidentity': 'd'}),
          ],
          identities: [
            IdentityRow.fromRow({
              'attnum': '1',
              'seqstart': '1000',
              'seqincrement': '1',
            }),
            IdentityRow.fromRow({
              'attnum': '2',
              'seqstart': '1',
              'seqincrement': '1',
            }),
          ],
        ),
      );
      expect(
        ddl,
        contains(
          'id bigint GENERATED ALWAYS AS IDENTITY (START WITH 1000) NOT NULL,',
        ),
      );
      expect(ddl, contains('n integer GENERATED BY DEFAULT AS IDENTITY\n'));
    });

    test('stored generated column never gets DEFAULT', () {
      final ddl = pg17.assemble(
        TableDdlSource(
          header: headerRow(),
          columns: [
            columnRow(1, 'total', 'integer', {
              'attgenerated': 's',
              'default_or_generation_expr': '(qty * 2)',
            }),
          ],
        ),
      );
      expect(
        ddl,
        contains('total integer GENERATED ALWAYS AS ((qty * 2)) STORED'),
      );
      expect(ddl, isNot(contains('DEFAULT')));
    });

    test('virtual generated column (PG18) is explicit', () {
      final ddl = pg18.assemble(
        TableDdlSource(
          header: headerRow(),
          columns: [
            columnRow(1, 'v', 'integer', {
              'attgenerated': 'v',
              'default_or_generation_expr': '(qty + 1)',
            }),
          ],
        ),
      );
      expect(
        ddl,
        contains('v integer GENERATED ALWAYS AS ((qty + 1)) VIRTUAL'),
      );
    });

    test('compression method is emitted (PG14+)', () {
      final ddl = pg17.assemble(
        TableDdlSource(
          header: headerRow(),
          columns: [
            columnRow(1, 'body', 'text', {'attcompression': 'l'}),
            columnRow(2, 'note', 'text', {'attcompression': 'p'}),
          ],
        ),
      );
      expect(ddl, contains('body text COMPRESSION lz4,'));
      expect(ddl, contains('note text COMPRESSION pglz\n'));
    });
  });

  group('NOT NULL by server version', () {
    final columns = [
      columnRow(1, 'a', 'integer', {'attnotnull': 't'}),
      columnRow(2, 'b', 'integer', {'attnotnull': 't'}),
      columnRow(3, 'c', 'integer', {'attnotnull': 't'}),
      columnRow(4, 'd', 'integer', {'attnotnull': 't'}),
    ];
    final notNulls = [
      constraintRow('orders_a_not_null', 'n', 'NOT NULL a', {'attnum': '1'}),
      constraintRow('b_required', 'n', 'NOT NULL b', {'attnum': '2'}),
      constraintRow('orders_c_not_null', 'n', 'NOT NULL c NO INHERIT', {
        'attnum': '3',
        'connoinherit': 't',
      }),
      constraintRow('d_later', 'n', 'NOT NULL d NOT VALID', {
        'attnum': '4',
        'convalidated': 'f',
      }),
    ];

    test('PG18 takes NOT NULL from contype n, never twice', () {
      final ddl = pg18.assemble(
        TableDdlSource(
          header: headerRow(),
          columns: columns,
          constraints: notNulls,
        ),
      );
      expect(ddl, contains('    a integer NOT NULL,\n'));
      expect(ddl, contains('    b integer CONSTRAINT b_required NOT NULL,\n'));
      expect(ddl, contains('    c integer NOT NULL NO INHERIT,\n'));
      expect(ddl, contains('    d integer\n'));
      expect(
        ddl,
        contains(
          'ALTER TABLE public.orders ADD CONSTRAINT d_later '
          'NOT NULL d NOT VALID;',
        ),
      );
      expect('NOT NULL'.allMatches(ddl).length, 4);
    });

    test('PG17 uses attnotnull only', () {
      final ddl = pg17.assemble(
        TableDdlSource(header: headerRow(), columns: columns),
      );
      expect('NOT NULL'.allMatches(ddl).length, 4);
      expect(ddl, contains('    d integer NOT NULL\n'));
    });
  });

  test('unlogged, access method, options, TOAST options and tablespace', () {
    final ddl = pg17.assemble(
      TableDdlSource(
        header: headerRow({
          'relpersistence': 'u',
          'access_method': 'columnar',
          'reloptions': '{fillfactor=70}',
          'toast_reloptions': '{autovacuum_enabled=false}',
          'tablespace': 'Fast Disk',
        }),
        columns: [columnRow(1, 'a', 'integer')],
      ),
    );
    expect(
      ddl,
      startsWith(
        'CREATE UNLOGGED TABLE public.orders (\n'
        '    a integer\n'
        ')\n'
        'USING columnar\n'
        'WITH (fillfactor=70, toast.autovacuum_enabled=false)\n'
        'TABLESPACE "Fast Disk";\n',
      ),
    );
  });

  test('heap access method is not printed', () {
    final ddl = pg17.assemble(TableDdlSource(header: headerRow()));
    expect(ddl, startsWith('CREATE TABLE public.orders (\n);\n'));
  });

  test('grants skip the owner and group per grantee', () {
    final ddl = pg17.assemble(
      TableDdlSource(
        header: headerRow({'relacl': '{app=arwdDxtm/app,reader=r/app}'}),
        grants: [
          grantRow('app', 'SELECT', owner: true),
          grantRow('app', 'INSERT', owner: true),
          grantRow('PUBLIC', 'SELECT'),
          grantRow('"Report Role"', 'INSERT'),
          grantRow('"Report Role"', 'SELECT'),
          grantRow('"Report Role"', 'UPDATE', grantable: true),
        ],
      ),
    );
    expect(
      ddl,
      contains(
        'GRANT SELECT ON TABLE public.orders TO PUBLIC;\n'
        'GRANT INSERT, SELECT ON TABLE public.orders TO "Report Role";\n'
        'GRANT UPDATE ON TABLE public.orders TO "Report Role" '
        'WITH GRANT OPTION;\n',
      ),
    );
    expect(ddl, isNot(matches(RegExp('GRANT [^;]* TO app'))));
  });

  test('odd names are quoted everywhere', () {
    final ddl = pg17.assemble(
      TableDdlSource(
        header: headerRow({
          'schema': 'Sales Data',
          'name': 'Mixed Case',
          'owner': 'Owner"Role',
          'comment': "it's",
        }),
        columns: [
          columnRow(1, 'select', 'integer', {'comment': 'kw'}),
          columnRow(2, 'we"ird', 'text'),
        ],
      ),
    );
    expect(ddl, contains('CREATE TABLE "Sales Data"."Mixed Case" (\n'));
    expect(ddl, contains('    "select" integer,\n    "we""ird" text\n'));
    expect(ddl, contains('OWNER TO "Owner""Role";'));
    expect(
      ddl,
      contains("COMMENT ON TABLE \"Sales Data\".\"Mixed Case\" IS 'it''s';"),
    );
    expect(
      ddl,
      contains(
        'COMMENT ON COLUMN "Sales Data"."Mixed Case"."select" IS \'kw\';',
      ),
    );
  });

  test('comments on table, columns, local constraints and indexes', () {
    final ddl = pg17.assemble(
      TableDdlSource(
        header: headerRow({'comment': 'All orders'}),
        columns: [
          columnRow(1, 'id', 'integer', {'comment': 'key'}),
        ],
        constraints: [
          constraintRow('orders_pkey', 'p', 'PRIMARY KEY (id)', {
            'comment': 'pk',
          }),
          constraintRow('inherited', 'c', 'CHECK (true)', {
            'conislocal': 'f',
            'comment': 'not mine',
          }),
        ],
        indexes: [
          indexRow('orders_pkey', 'CREATE UNIQUE INDEX orders_pkey ...', {
            'is_constraint': 't',
            'comment': 'constraint index',
          }),
          indexRow('orders_x', 'CREATE INDEX orders_x ON public.orders (x)', {
            'comment': 'idx',
          }),
        ],
      ),
    );
    expect(
      ddl,
      endsWith(
        "COMMENT ON TABLE public.orders IS 'All orders';\n"
        "COMMENT ON COLUMN public.orders.id IS 'key';\n"
        "COMMENT ON CONSTRAINT orders_pkey ON public.orders IS 'pk';\n"
        "COMMENT ON INDEX public.orders_x IS 'idx';\n",
      ),
    );
  });

  test('ColumnRow parses server text', () {
    final c = columnRow(7, 'x', 'integer', {
      'attnotnull': 't',
      'attislocal': 'f',
      'attfdwoptions': '{"column_name=remote x"}',
    });
    expect(c.attnum, 7);
    expect(c.notNull, isTrue);
    expect(c.isLocal, isFalse);
    expect(c.fdwOptions, ['column_name=remote x']);
  });

  test('a NULL required column is a FormatException', () {
    expect(
      () => ColumnRow.fromRow({'attnum': '1', 'attname': null, 'type': 'int'}),
      throwsFormatException,
    );
    expect(() => requireText({}, 'x'), throwsFormatException);
  });
}
